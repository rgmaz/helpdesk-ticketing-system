import { useNavigate } from 'react-router-dom'
import type { Ticket, TicketStatus } from '../api/types'
import { humanize } from '../lib/format'
import { Empty, ErrorNote, Pager, PriorityBadge, SLABadge, Spinner, StatusBadge, TimeStamp } from './ui'

/**
 * Columns and the query key each one sends.
 *
 * These keys are exactly the server's sort whitelist, which GET /meta
 * advertises: a sort the API would reject with a 400 is never offered in the
 * first place, so the table cannot produce a request the server refuses.
 */
interface SortSpec {
  label: string
  /** Undefined means the column is display-only. */
  key?: string
}

const COLUMNS: SortSpec[] = [
  { label: 'Ticket', key: 'number' },
  { label: 'Summary' },
  { label: 'Status', key: 'status' },
  { label: 'Priority', key: 'priority' },
  { label: 'SLA', key: 'due' },
  { label: 'Assignee', key: 'assignee_name' },
  { label: 'Updated', key: 'updated' },
]

export interface TicketTableProps {
  tickets: Ticket[]
  loading: boolean
  error: string | null
  page: number
  pages: number
  total: number
  limit: number
  sortBy: string
  sortDir: 'asc' | 'desc'
  /** Hides the requester column: staff already know whose it is by assignment. */
  showRequester?: boolean
  onSort: (key: string) => void
  onPage: (page: number) => void
  /** Search results render the FTS5 excerpt instead of the description. */
  snippets?: boolean
  emptyTitle?: string
  emptyHint?: string
}

export function TicketTable({
  tickets,
  loading,
  error,
  page,
  pages,
  total,
  limit,
  sortBy,
  sortDir,
  showRequester,
  onSort,
  onPage,
  snippets,
  emptyTitle = 'No tickets match',
  emptyHint,
}: TicketTableProps) {
  const navigate = useNavigate()

  if (error) {
    return (
      <div className="card card-pad">
        <ErrorNote>{error}</ErrorNote>
      </div>
    )
  }
  if (loading && tickets.length === 0) return <Spinner label="Loading tickets…" />
  if (tickets.length === 0) return <Empty title={emptyTitle} hint={emptyHint} />

  return (
    <div className="table-wrap">
      <table className="tbl">
        <thead>
          <tr>
            {COLUMNS.map(({ label, key }) =>
              // Narrowed once so the sort callback is known to get a string: a
              // column without a key is display-only and renders no button.
              !key ? (
                <th key={label}>{label}</th>
              ) : (
                <SortHeader key={key} label={label} field={key} active={sortBy} dir={sortDir} onSort={onSort} />
              ),
            )}
            {showRequester && <th>Requester</th>}
          </tr>
        </thead>
        <tbody>
          {tickets.map((ticket) => (
            <tr
              key={ticket.id}
              className="clickable"
              onClick={() => navigate(`/tickets/${ticket.id}`)}
              tabIndex={0}
              onKeyDown={(event) => {
                // Rows are links to a detail page, so they must be reachable
                // and activatable from the keyboard.
                if (event.key === 'Enter') navigate(`/tickets/${ticket.id}`)
              }}
            >
              <td className="mono nowrap">{ticket.ticket_number}</td>
              <td style={{ maxWidth: 380 }}>
                <div className="truncate" style={{ fontWeight: 500 }}>
                  {ticket.title}
                </div>
                <div className="faint truncate" style={{ fontSize: '0.75rem' }}>
                  {ticket.category}
                  {ticket.comment_count > 0 && ` · ${ticket.comment_count} comment${ticket.comment_count === 1 ? '' : 's'}`}
                  {ticket.escalation_level > 0 && ` · escalated L${ticket.escalation_level}`}
                </div>
                {snippets && ticket.snippet && (
                  // FTS5 wraps matches in <mark>. The snippet is generated by
                  // the server from ticket text, never from user input typed
                  // into a form here.
                  <div
                    className="truncate"
                    style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}
                    dangerouslySetInnerHTML={{ __html: ticket.snippet }}
                  />
                )}
              </td>
              <td className="nowrap">
                <StatusBadge value={ticket.status} />
              </td>
              <td className="nowrap">
                <PriorityBadge value={ticket.priority} />
              </td>
              <td className="nowrap">
                <SLACell ticket={ticket} />
              </td>
              <td className="truncate nowrap" style={{ maxWidth: 150 }}>
                {ticket.assignee_name ?? <span className="faint">Unassigned</span>}
              </td>
              <td className="nowrap muted">
                <TimeStamp value={ticket.updated_at} />
              </td>
              {showRequester && <td className="truncate nowrap">{ticket.requester_name}</td>}
            </tr>
          ))}
        </tbody>
      </table>
      <Pager page={page} pages={pages} total={total} limit={limit} onChange={onPage} />
    </div>
  )
}

/**
 * A sortable column header.
 *
 * aria-sort belongs on the header cell, not the button, so assistive technology
 * announces the table's ordering rather than just that a control is pressed.
 */
function SortHeader({
  label,
  field,
  active,
  dir,
  onSort,
}: {
  label: string
  field: string
  active: string
  dir: 'asc' | 'desc'
  onSort: (key: string) => void
}) {
  const isActive = active === field
  return (
    <th aria-sort={isActive ? (dir === 'asc' ? 'ascending' : 'descending') : 'none'}>
      <button type="button" onClick={() => onSort(field)}>
        {label}
        {isActive && (
          <span className="arrow" aria-hidden="true">
            {dir === 'asc' ? '▲' : '▼'}
          </span>
        )}
      </button>
    </th>
  )
}

/**
 * The SLA cell.
 *
 * A ticket with no deadline — closed, or created before a policy was attached
 * — has no clock to show, so the cell says stopped rather than rendering a
 * misleading zero.
 */
function SLACell({ ticket }: { ticket: Ticket }) {
  if (ticket.status === 'closed') {
    return <span className="faint nowrap">{ticket.resolution_breached ? 'Missed' : 'Met'}</span>
  }
  const remaining = ticket.sla_resolution_remaining_seconds
  if (remaining === undefined) {
    return <span className="faint nowrap">No deadline</span>
  }
  return (
    <SLABadge
      state={ticket.sla_state}
      detail={`Resolution due ${ticket.sla_resolution_due_at ?? 'unknown'}`}
    />
  )
}

/** The status filter chips, with the per-status counts the list endpoint returns. */
export function StatusChips({
  value,
  counts,
  onChange,
}: {
  value: TicketStatus[]
  counts?: Partial<Record<TicketStatus, number>>
  onChange: (next: TicketStatus[]) => void
}) {
  const labels: Record<TicketStatus, string> = {
    open: 'Open',
    in_progress: 'In progress',
    pending: 'Pending',
    resolved: 'Resolved',
    closed: 'Closed',
    reopened: 'Reopened',
  }

  const toggle = (status: TicketStatus) => {
    onChange(value.includes(status) ? value.filter((s) => s !== status) : [...value, status])
  }

  return (
    <div className="chips" role="group" aria-label="Filter by status">
      {Object.entries(labels).map(([status, label]) => {
        const count = counts?.[status as TicketStatus]
        const on = value.includes(status as TicketStatus)
        return (
          <button
            key={status}
            type="button"
            className={`chip${on ? ' on' : ''}`}
            aria-pressed={on}
            onClick={() => toggle(status as TicketStatus)}
          >
            {label}
            {count !== undefined && count > 0 && <span className="count">{count}</span>}
          </button>
        )
      })}
    </div>
  )
}

/** Sort control for columns that the table does not render a header for. */
export function SortSelect({
  value,
  fields,
  onChange,
}: {
  value: string
  fields: string[]
  onChange: (next: string) => void
}) {
  return (
    <select
      value={value}
      onChange={(event) => onChange(event.target.value)}
      aria-label="Sort by"
      style={{ width: 'auto' }}
    >
      {fields.map((field) => (
        <option key={field} value={field}>
          Sort: {humanize(field)}
        </option>
      ))}
    </select>
  )
}
